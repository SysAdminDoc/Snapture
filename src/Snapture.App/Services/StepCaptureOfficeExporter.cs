    private static string CreateSlideXml(
        string title,
        string? caption,
        string? imageRelationship,
        ImageDimensions? dimensions,
        uint slideNumber)
    {
        var titleShape = CreateTextShapeXml(
            2,
            "Title",
            457200,
            228600,
            11_277_600,
            600_000,
            title,
            2800,
            bold: true);
        var captionShape = string.IsNullOrWhiteSpace(caption)
            ? string.Empty
            : CreateTextShapeXml(
                3,
                "Caption",
                457200,
                900000,
                11_277_600,
                650000,
                caption,
                1800,
                bold: false);
        var imageShape = imageRelationship is not null && dimensions is not null
            ? CreatePictureXml(imageRelationship, dimensions.Value, 4)
            : string.Empty;

        return $"""
        <?xml version="1.0" encoding="UTF-8" standalone="yes"?>
        <p:sld xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships" xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main">
          <p:cSld name="Step {slideNumber}">
            <p:spTree>
              <p:nvGrpSpPr><p:cNvPr id="1" name=""/><p:cNvGrpSpPr/><p:nvPr/></p:nvGrpSpPr>
              <p:grpSpPr><a:xfrm><a:off x="0" y="0"/><a:ext cx="0" cy="0"/><a:chOff x="0" y="0"/><a:chExt cx="0" cy="0"/></a:xfrm></p:grpSpPr>
              {titleShape}
              {captionShape}
              {imageShape}
            </p:spTree>
          </p:cSld>
          <p:clrMapOvr><a:masterClrMapping/></p:clrMapOvr>
        </p:sld>
        """;
    }

    private static string CreateTextShapeXml(
        uint id,
        string name,
        long x,
        long y,
        long width,
        long height,
        string? text,
        int fontSize,
        bool bold)
    {
        var paragraphs = string.Join(
            string.Empty,
            (text ?? string.Empty)
                .Replace("\r\n", "\n", StringComparison.Ordinal)
                .Split('\n')
                .Select(line =>
                    $"<a:p><a:r><a:rPr lang=\"en-US\" sz=\"{fontSize}\"{(bold ? " b=\"1\"" : string.Empty)}/><a:t xml:space=\"preserve\">{EscapeXml(line)}</a:t></a:r><a:endParaRPr lang=\"en-US\"/></a:p>"));
        return $"""
        <p:sp>
          <p:nvSpPr><p:cNvPr id="{id}" name="{EscapeXml(name)}"/><p:cNvSpPr txBox="1"/><p:nvPr/></p:nvSpPr>
          <p:spPr><a:xfrm><a:off x="{x}" y="{y}"/><a:ext cx="{width}" cy="{height}"/></a:xfrm><a:prstGeom prst="rect"><a:avLst/></a:prstGeom></p:spPr>
          <p:txBody><a:bodyPr wrap="square" anchor="t"/><a:lstStyle/>{paragraphs}</p:txBody>
        </p:sp>
        """;
    }

    private static string CreatePictureXml(string relationshipId, ImageDimensions dimensions, uint id)
    {
        var size = FitInside(dimensions.Width, dimensions.Height, 11_277_600, 4_950_000);
        var x = (SlideWidth - size.Width) / 2;
        var y = 1_650_000;
        return $"""
        <p:pic>
          <p:nvPicPr><p:cNvPr id="{id}" name="Step image"/><p:cNvPicPr preferRelativeResize="0"/><p:nvPr/></p:nvPicPr>
          <p:blipFill><a:blip r:embed="{relationshipId}"/><a:stretch><a:fillRect/></a:stretch></p:blipFill>
          <p:spPr><a:xfrm><a:off x="{x}" y="{y}"/><a:ext cx="{size.Width}" cy="{size.Height}"/></a:xfrm><a:prstGeom prst="rect"><a:avLst/></a:prstGeom></p:spPr>
        </p:pic>
        """;
    }

    private static void WritePart(OpenXmlPart part, string xml)
    {
        using var stream = part.GetStream(FileMode.Create, FileAccess.Write);
        using var writer = new StreamWriter(stream, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
        writer.Write(xml.Trim());
    }

    private static string EscapeXml(string value) =>
        SecurityElement.Escape(value) ?? string.Empty;

    private static PartTypeInfo GetImagePartType(string path) =>
        Path.GetExtension(path).ToLowerInvariant() switch
        {
            ".jpg" or ".jpeg" => ImagePartType.Jpeg,
            ".gif" => ImagePartType.Gif,
            ".bmp" => ImagePartType.Bmp,
            _ => ImagePartType.Png
        };

    private static ImageDimensions? ReadImageDimensions(string path)
    {
        try
        {
            using var bitmap = SKBitmap.Decode(path);
            return bitmap is null || bitmap.Width <= 0 || bitmap.Height <= 0
                ? null
                : new ImageDimensions(bitmap.Width, bitmap.Height);
        }
        catch
        {
            return null;
        }
    }

    private static ImageDimensions FitInside(int width, int height, long maxWidth, long maxHeight)
    {
        var scale = Math.Min((double)maxWidth / width, (double)maxHeight / height);
        return new ImageDimensions(
            Math.Max(1, (int)Math.Round(width * scale)),
            Math.Max(1, (int)Math.Round(height * scale)));
    }

    private readonly record struct ImageDimensions(int Width, int Height);
}
