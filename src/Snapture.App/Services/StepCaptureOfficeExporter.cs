/// <summary>Exports Step Capture sessions to editable Word and PowerPoint documents.</summary>
public static class StepCaptureOfficeExporter
{
    private const long EmusPerInch = 914400;
    private const long DocxMaxWidth = 6_500_000;
    private const long DocxMaxHeight = 8_800_000;
    private const long SlideWidth = 12_192_000;
    private const long SlideHeight = 6_858_000;

    public static string ExportDocx(string outputPath, string title, IEnumerable<StepCaptureExporter.StepEntry> entries)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(outputPath);
        var items = entries?.ToList() ?? throw new ArgumentNullException(nameof(entries));
        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(outputPath))!);

        using var document = WordprocessingDocument.Create(
            outputPath,
            WordprocessingDocumentType.Document);
        var mainPart = document.AddMainDocumentPart();
        var body = new W.Body();
        mainPart.Document = new W.Document(body);

        body.Append(CreateWordParagraph(title, "36", bold: true));
        body.Append(CreateWordParagraph(
            $"Generated by Snapture · {DateTime.Now:yyyy-MM-dd HH:mm} · {items.Count} steps",
            "20",
            bold: false));

        uint drawingId = 1;
        foreach (var entry in items)
        {
            body.Append(CreateWordParagraph($"Step {entry.Number}", "28", bold: true));
            AppendWordCaption(body, entry.Caption);
            AppendWordInputTrack(body, entry);
            var dimensions = ReadImageDimensions(entry.FilePath);
            if (dimensions is null) continue;

            var imagePart = mainPart.AddImagePart(GetImagePartType(entry.FilePath));
            using (var stream = File.OpenRead(entry.FilePath))
                imagePart.FeedData(stream);

            var size = FitInside(dimensions.Value.Width, dimensions.Value.Height, DocxMaxWidth, DocxMaxHeight);
            var drawing = CreateWordImageDrawing(
                mainPart.GetIdOfPart(imagePart),
                size.Width,
                size.Height,
                drawingId++,
                $"Step {entry.Number}");
            body.Append(new W.Paragraph(new W.Run(drawing)));
        }

        body.Append(new W.SectionProperties(
            new W.PageSize { Width = 12240, Height = 15840 },
            new W.PageMargin { Top = 720, Right = 720, Bottom = 720, Left = 720 }));
        mainPart.Document.Save();
        return outputPath;
    }

    public static string ExportPptx(string outputPath, string title, IEnumerable<StepCaptureExporter.StepEntry> entries)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(outputPath);
        var items = entries?.ToList() ?? throw new ArgumentNullException(nameof(entries));
        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(outputPath))!);

        using var document = PresentationDocument.Create(
            outputPath,
            PresentationDocumentType.Presentation);
        var presentationPart = document.AddPresentationPart();
        var masterPart = presentationPart.AddNewPart<SlideMasterPart>("rIdMaster");
        var layoutPart = masterPart.AddNewPart<SlideLayoutPart>("rIdLayout");
        var themePart = masterPart.AddNewPart<ThemePart>("rIdTheme");
        layoutPart.AddPart(masterPart, "rIdMaster");

        WritePart(masterPart, CreateSlideMasterXml());
        WritePart(layoutPart, CreateSlideLayoutXml());
        WritePart(themePart, CreateThemeXml());

        var presentation = new P.Presentation
        {
            SlideMasterIdList = new P.SlideMasterIdList(
                new P.SlideMasterId
                {
                    Id = 2_147_483_648U,
                    RelationshipId = presentationPart.GetIdOfPart(masterPart)
                }),
            SlideIdList = new P.SlideIdList(),
            SlideSize = new P.SlideSize { Cx = (int)SlideWidth, Cy = (int)SlideHeight },
            NotesSize = new P.NotesSize { Cx = 6_858_000, Cy = 9_144_000 }
        };
        presentationPart.Presentation = presentation;

        AddSlide(
            presentationPart,
            layoutPart,
            presentation.SlideIdList!,
            title,
            $"Step Capture · {items.Count} steps · Generated by Snapture",
            imagePath: null,
            slideNumber: 1);

        uint slideNumber = 2;
        foreach (var entry in items)
        {
            AddSlide(
                presentationPart,
                layoutPart,
                presentation.SlideIdList!,
                $"Step {entry.Number}",
                BuildOfficeCaption(entry),
                entry.FilePath,
                slideNumber++);
        }

        presentationPart.Presentation.Save();
        return outputPath;
    }

    private static void AddSlide(
        PresentationPart presentationPart,
        SlideLayoutPart layoutPart,
        P.SlideIdList slideIds,
        string title,
        string? caption,
        string? imagePath,
        uint slideNumber)
    {
        var slidePart = presentationPart.AddNewPart<SlidePart>();
        slidePart.AddPart(layoutPart, "rIdLayout");

        string? imageRelationship = null;
        ImageDimensions? dimensions = null;
        var sourcePath = imagePath;
        if (sourcePath is not null && File.Exists(sourcePath))
        {
            dimensions = ReadImageDimensions(sourcePath);
            if (dimensions is not null)
            {
                var imagePart = slidePart.AddImagePart(GetImagePartType(sourcePath), "rIdImage");
                using var stream = File.OpenRead(sourcePath);
                imagePart.FeedData(stream);
                imageRelationship = slidePart.GetIdOfPart(imagePart);
            }
        }

        WritePart(slidePart, CreateSlideXml(title, caption, imageRelationship, dimensions, slideNumber));
        slideIds.Append(new P.SlideId
        {
            Id = 255U + slideNumber,
            RelationshipId = presentationPart.GetIdOfPart(slidePart)
        });
    }

    private static W.Paragraph CreateWordParagraph(string text, string fontSize, bool bold)
    {
        var properties = new W.RunProperties();
        if (bold) properties.AppendChild(new W.Bold());
        properties.AppendChild(new W.FontSize { Val = fontSize });
        return new W.Paragraph(new W.Run(properties, new W.Text(text ?? string.Empty)));
    }

    private static void AppendWordCaption(W.Body body, string? caption)
    {
        if (string.IsNullOrWhiteSpace(caption)) return;
        foreach (var line in caption.Replace("\r\n", "\n", StringComparison.Ordinal).Split('\n'))
            body.Append(CreateWordParagraph(line, "22", bold: false));
    }

    private static void AppendWordInputTrack(W.Body body, StepCaptureExporter.StepEntry entry)
    {
        var track = StepCaptureInputFormatter.FormatOfficeCaption(entry.Keystrokes, entry.Clicks);
        if (track is not null)
            body.Append(CreateWordParagraph(track, "18", bold: false));
    }

    private static string? BuildOfficeCaption(StepCaptureExporter.StepEntry entry)
    {
        var track = StepCaptureInputFormatter.FormatOfficeCaption(entry.Keystrokes, entry.Clicks);
        if (string.IsNullOrWhiteSpace(entry.Caption))
            return track;
        if (track is null)
            return entry.Caption;
        return $"{entry.Caption.Trim()}\n{track}";
    }

    private static W.Drawing CreateWordImageDrawing(
        string relationshipId,
        long width,
        long height,
        uint drawingId,
        string name)
    {
        return new W.Drawing(
            new DW.Inline(
                new DW.Extent { Cx = width, Cy = height },
                new DW.EffectExtent
                {
                    LeftEdge = 0,
                    TopEdge = 0,
                    RightEdge = 0,
                    BottomEdge = 0
                },
                new DW.DocProperties { Id = drawingId, Name = name },
                new DW.NonVisualGraphicFrameDrawingProperties(
                    new A.GraphicFrameLocks { NoChangeAspect = true }),
                new A.Graphic(
                    new A.GraphicData(
                        new PIC.Picture(
                            new PIC.NonVisualPictureProperties(
                                new PIC.NonVisualDrawingProperties { Id = drawingId, Name = name },
                                new PIC.NonVisualPictureDrawingProperties()),
                            new PIC.BlipFill(
                                new A.Blip { Embed = relationshipId },
                                new A.Stretch(new A.FillRectangle())),
                            new PIC.ShapeProperties(
                                new A.Transform2D(
                                    new A.Offset { X = 0, Y = 0 },
                                    new A.Extents { Cx = width, Cy = height }),
                                new A.PresetGeometry(new A.AdjustValueList())
                                {
                                    Preset = A.ShapeTypeValues.Rectangle
                                })))
                    {
                        Uri = "http://schemas.openxmlformats.org/drawingml/2006/picture"
                    })));
    }

